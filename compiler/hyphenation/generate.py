#!/usr/bin/env python3
"""Generates Uzbek hyphenation patterns (Latin and Cyrillic) for TeX.

TeX Live has no Uzbek patterns, so babel's uz-Latn / uz-Cyrl languages do not
hyphenate at all. Uzbek syllables follow simple rules (O'zbek tilining asosiy
imlo qoidalari), which are written here as Liang patterns:

* a consonant (or sh, ch, ng, g', y...) followed by a vowel starts a new
  syllable: ki-tob, mak-tab, de-ngiz, ma-shi-na, o'q-ish;
* two vowels next to each other belong to different syllables: sa-no-at;
* the digraphs sh, ch, ng and the letters o', g' are never split;
* the tutuq belgisi (') stays with the letter before it: ma'-no, san'-at;
* word-initial consonant clusters of loanwords are not split off: struk-tu-ra;
* at least two letters stay on each line (\\lefthyphenmin = \\righthyphenmin = 2).

Usage: python3 generate.py  (writes hyph-uz.tex and hyph-uz.pat.txt next to it)
"""
from pathlib import Path

OKINA = "ʻ"  # ʻ in oʻ, gʻ
TUTUQ = "ʼ"  # ʼ (tutuq belgisi)

LATIN_VOWELS = "aeiou"
LATIN_CONSONANTS = "bcdfghjklmnpqrstvxyz"
LATIN_DIGRAPHS = ["sh", "ch", "ng", "g" + OKINA]

CYR_VOWELS = "аеёиоуўэюя"
CYR_CONSONANTS = "бвгғджзйкқлмнпрстфхҳцчшщ"


def patterns() -> list[str]:
    out: set[str] = set()

    # --- Latin -------------------------------------------------------------
    for v in LATIN_VOWELS:
        for c in LATIN_CONSONANTS:
            out.add(f"1{c}{v}")  # break before a consonant that starts a syllable
        for d in LATIN_DIGRAPHS:
            out.add(f"1{d}{v}")  # ... or before a digraph
        for w in LATIN_VOWELS:
            out.add(f"{v}1{w}")  # vowels in a row: separate syllables
            out.add(f"o{OKINA}1{w}")
        out.add(f"{TUTUQ}1{v}")  # san'-at
    # Never inside sh, ch, ng, o', g'; never before the tutuq belgisi.
    out |= {"s2h", "c2h", "n2g", f"o2{OKINA}", f"g2{OKINA}", f"2{TUTUQ}"}
    # n + g' are two letters (ton-g'a), unlike the digraph ng.
    out.add(f"n3g{OKINA}")
    # Word-initial consonant clusters (stol, sport, struktura, shkaf, shtrix):
    # nothing without a vowel may be left at the end of a line.
    for a in list(LATIN_CONSONANTS) + ["sh", "ch"]:
        for b in LATIN_CONSONANTS:
            out.add(f".{a}{b}2")
    for d in ("sh", "ch"):
        for b in LATIN_CONSONANTS:
            out.add(f".{d}2{b}")
    # A lone o' is one letter: no o'-zi at the start, no ...-o' at the end.
    out |= {f".o{OKINA}2", f"2o{OKINA}."}

    # --- Cyrillic ------------------------------------------------------------
    for v in CYR_VOWELS:
        for c in CYR_CONSONANTS:
            out.add(f"1{c}{v}")
        for w in CYR_VOWELS:
            out.add(f"{v}1{w}")
        out.add(f"ъ1{v}")  # санъ-ат
        out.add(f"ь1{v}")
        out.add(f"1нг{v}")  # де-нгиз
    out |= {"н2г", "2ъ", "2ь"}
    for a in CYR_CONSONANTS:
        for b in CYR_CONSONANTS:
            out.add(f".{a}{b}2")

    return merge(out)


def merge(raw: set[str]) -> list[str]:
    """TeX rejects two patterns with the same letters: keep the highest digit per position."""
    by_letters: dict[str, list[int]] = {}
    for p in raw:
        letters = "".join(ch for ch in p if not ch.isdigit())
        values = [0] * (len(letters) + 1)
        i = 0
        for ch in p:
            if ch.isdigit():
                values[i] = max(values[i], int(ch))
            else:
                i += 1
        old = by_letters.setdefault(letters, values)
        by_letters[letters] = [max(a, b) for a, b in zip(old, values)]
    out = []
    for letters, values in by_letters.items():
        text = "".join((str(values[i]) if values[i] else "") + ch for i, ch in enumerate(letters))
        out.append(text + (str(values[-1]) if values[-1] else ""))
    return sorted(out)


HEADER = """% hyph-uz.tex: Uzbek hyphenation patterns (Latin and Cyrillic script).
% Generated by compiler/hyphenation/generate.py from the syllable rules of
% Uzbek orthography; do not edit by hand. Part of Oversells (MIT licence).
%
% Latin letters o' and g' use U+02BB (modifier letter turned comma), the
% tutuq belgisi uses U+02BC (modifier letter apostrophe).
"""


def main() -> None:
    here = Path(__file__).resolve().parent
    pats = patterns()
    body = "\n".join(pats)
    (here / "hyph-uz.tex").write_text(f"{HEADER}\\patterns{{\n{body}\n}}\n", encoding="utf-8")
    (here / "hyph-uz.pat.txt").write_text(body + "\n", encoding="utf-8")
    print(f"{len(pats)} patterns")


if __name__ == "__main__":
    main()
